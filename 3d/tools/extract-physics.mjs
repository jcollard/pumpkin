// Copies the game's simulation code out of the original index.html into an
// ES module, so the 3D viewer runs exactly the same physics as the 2D game.
//
//   node tools/extract-physics.mjs [path/to/index.html] [output.js]
//
// Defaults assume this folder sits at <fork>/3d/, next to the game's index.html.
// Nothing in the physics is edited: we keep every line before the game's UI
// code starts and add an export list at the end.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const input = resolve(process.argv[2] ?? resolve(here, '../../index.html'));
const output = resolve(process.argv[3] ?? resolve(here, '../src/physics.js'));

const html = readFileSync(input, 'utf8');
const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]);
if (!scripts.length) throw Error('No <script> found in ' + input);
const code = scripts.reduce((a, b) => (b.length > a.length ? b : a));
const lines = code.split('\n');

// The UI begins at the first line that touches the page.
const uiStart = lines.findIndex(l => /document\.querySelector\('#app'\)|new Image\(\)/.test(l));
if (uiStart < 0) throw Error('Could not find where the UI code starts.');
const logic = lines.slice(0, uiStart).join('\n');

const wanted = ['PHYSICS_VERSION', 'tracks', 'varieties', 'keys', 'motion', 'simulate', 'simulateFleet',
  'sampleSimulation', 'leaderAt', 'circuitStandings', 'decode', 'encode', 'validate', 'properties', 'inspection', 'award',
  'shapeData', 'shapeOutline', 'shapeRadius', 'initialPose', 'terrain', 'varietyOf', 'artificialEffect', 'coreFill',
  'enhancement', 'LEVEL_LIMIT'];
const declared = name => new RegExp(`(?:function\\*?\\s+${name}\\s*\\(|(?:const|let|var)\\s+(?:[^;]*?[,\\s])?${name}\\s*=)`).test(logic);
const missing = wanted.filter(n => !declared(n));
if (missing.length) throw Error('Physics code no longer declares: ' + missing.join(', '));

const version = logic.match(/PHYSICS_VERSION\s*=\s*([^,;\n]+)/)?.[1] ?? '?';
writeFileSync(output,
  `// GENERATED by tools/extract-physics.mjs from ${input.split('/').slice(-2).join('/')} — do not edit.\n` +
  `// Physics version ${version}. Re-run the tool whenever the game's index.html changes.\n` +
  logic + `\nexport {${wanted.join(', ')}};\n`);
console.log(`Wrote ${output} (${uiStart} lines, physics version ${version}).`);
