// Copies the original game's 2D inspector and pumpkin drawing code out of its index.html,
// so the 3D viewer can show the game's own inspection animation as a pop-up.
//
//   node tools/extract-inspector.mjs [path/to/index.html] [output.js]
//
// Like extract-physics.mjs, nothing is rewritten: the named functions are copied verbatim.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const input = resolve(process.argv[2] ?? resolve(here, '../../index.html'));
const output = resolve(process.argv[3] ?? resolve(here, '../src/inspector2d.js'));
const html = readFileSync(input, 'utf8');
const code = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]).reduce((a, b) => (b.length > a.length ? b : a));

// Brace matching that skips strings, template literals and comments.
function blockEnd(src, open) {
  let depth = 0, i = open, mode = null;
  for (; i < src.length; i++) {
    const c = src[i], n = src[i + 1];
    if (mode === '//') { if (c === '\n') mode = null; continue; }
    if (mode === '/*') { if (c === '*' && n === '/') { mode = null; i++; } continue; }
    if (mode) { if (c === '\\') { i++; continue; } if (c === mode) mode = null; continue; }
    if (c === '/' && n === '/') { mode = '//'; i++; continue; }
    if (c === '/' && n === '*') { mode = '/*'; i++; continue; }
    if (c === '"' || c === "'" || c === '`') { mode = c; continue; }
    if (c === '{') depth++;
    else if (c === '}' && --depth === 0) return i + 1;
  }
  throw Error('Unbalanced braces');
}
function fn(name) {
  const m = new RegExp(`function\\s+${name}\\s*\\(`).exec(code);
  if (!m) throw Error(`The game no longer has function ${name}()`);
  return code.slice(m.index, blockEnd(code, code.indexOf('{', code.indexOf(')', m.index))));
}
function constLine(name) {
  const m = new RegExp(`(?:^|[;\\n])\\s*const\\s+${name}\\s*=`).exec(code);
  if (!m) throw Error(`The game no longer has const ${name}`);
  const start = code.indexOf('const', m.index);
  let end = start, depth = 0, mode = null;
  for (; end < code.length; end++) { // up to the first top-level ; or newline
    const c = code[end];
    if (mode) { if (c === '\\') { end++; continue; } if (c === mode) mode = null; continue; }
    if (c === '"' || c === "'" || c === '`') { mode = c; continue; }
    if ('([{'.includes(c)) depth++; else if (')]}'.includes(c)) depth--;
    else if ((c === ';' || c === '\n') && depth === 0) break;
  }
  return code.slice(start, end) + ';';
}

const FUNCTIONS = ['canvasContext', 'pumpkinShape', 'photoCrop', 'seedMass', 'coatSparkles', 'drawGrooves', 'tintVariety', 'drawStem', 'renderPumpkin', 'inspectorFigure'];
const CONSTS = ['teamColors', 'nameOf'];
const atlas = /pumpkinAtlas\.src\s*=\s*"(data:image\/[a-z]+;base64,[A-Za-z0-9+/=]+)"/.exec(code)?.[1];
if (!atlas) throw Error('Could not find the pumpkin photo atlas.');

const body = [
  `// GENERATED by tools/extract-inspector.mjs from ${input.split('/').slice(-2).join('/')} — do not edit.`,
  `// The original game's 2D pumpkin and inspector drawing, copied verbatim.`,
  `import {shapeOutline, properties, varietyOf, coreFill, enhancement, artificialEffect, LEVEL_LIMIT, shapeRadius} from './physics.js';`,
  `let coatBurst = null; // the game's coat-change sparkle state; never active here`,
  `const pumpkinAtlas = new Image();`,
  `pumpkinAtlas.src = ${JSON.stringify(atlas)};`,
  ...CONSTS.map(constLine),
  ...FUNCTIONS.map(fn),
  `export {${[...FUNCTIONS, ...CONSTS, 'pumpkinAtlas'].join(', ')}};`,
].join('\n');
writeFileSync(output, body + '\n');
console.log(`Wrote ${output} (${(body.length / 1024).toFixed(0)} KB, atlas ${(atlas.length / 1024).toFixed(0)} KB).`);
